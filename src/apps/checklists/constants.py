from django.db import models


class ChecklistTypes(models.TextChoices):
    """
    Бизнес-типы шаблонов чек-листов.

    Определяют жизненный цикл и назначение бланка:
    - INSPECTION: Регулярный плановый осмотр оборудования.
    - ACCEPTANCE: Приемка оборудования перед началом работы.
    - HANDOVER: Сдача оборудования после завершения смены или этапа работ.
    """

    INSPECTION = 'INSPECTION', 'Осмотр'
    ACCEPTANCE = 'ACCEPTANCE', 'Приемка'
    HANDOVER = 'HANDOVER', 'Сдача'


class FieldTypes(models.TextChoices):
    """
    Поддерживаемые типы данных для динамической генерации полей (EAV-модель).

    Используются фронтендом для отрисовки соответствующих HTML-инпутов
    и бэкендом для строгой валидации (Type Casting) входящих значений.
    """

    STRING = 'STRING', 'Строка'
    INTEGER = 'INTEGER', 'Целое число'
    CHOICE = 'CHOICE', 'Выбор из списка'
    CHECKBOX = 'CHECKBOX', 'Чекбокс'
    DATE = 'DATE', 'Дата'
    AUTO_DATE = 'AUTO_DATE', 'Автоматическая дата'


class ShiftTypes(models.TextChoices):
    """
    Временные смены на производстве.
    Помогают фильтровать и группировать результаты проверок по сменам.
    """

    DAY = 'DAY', 'Дневная'
    NIGHT = 'NIGHT', 'Ночная'


class SignatureRoles(models.TextChoices):
    """
    Ролевая модель для процесса согласования (электронные подписи).

    Определяет права доступа и логику блокировки анкеты:
    - AUTHOR (Составитель): Тот, кто физически заполнил анкету. Подписывается автоматически.
    - APPROVER (Утверждающий): Переводит анкету в статус is_completed=True, блокируя изменения.
    - READER (Ознакомлен): Может ставить подпись даже на заблокированной анкете.
    """

    AUTHOR = 'AUTHOR', 'Составитель'
    APPROVER = 'APPROVER', 'Утверждающий (Подписант)'
    READER = 'READER', 'Ознакомлен (Читатель)'
